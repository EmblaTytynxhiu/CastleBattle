using UnityEngine;

public enum PieceMaterial { Wood, Stone, Metal, Glass, Ice, Light }

/// <summary>Weight and toughness of each material (per grid cell).</summary>
public static class MaterialStats
{
    public static float MassPerCell(PieceMaterial m)
    {
        switch (m)
        {
            case PieceMaterial.Stone: return 2.5f;
            case PieceMaterial.Metal: return 4f;
            case PieceMaterial.Glass: return 0.5f;
            case PieceMaterial.Ice: return 0.7f;
            case PieceMaterial.Light: return 0.6f;
            default: return 1f;
        }
    }

    public static float HealthPerCell(PieceMaterial m)
    {
        switch (m)
        {
            case PieceMaterial.Stone: return 90f;
            case PieceMaterial.Metal: return 150f;
            case PieceMaterial.Glass: return 15f;
            case PieceMaterial.Ice: return 25f;
            case PieceMaterial.Light: return 20f;
            default: return 40f;
        }
    }
}

/// <summary>
/// A castle piece: physics body + health. Shows cracked sprites as it gets damaged and breaks into debris.
/// Prefabs are generated by "Tools > Castle Battle > 7. Create Game Prefabs + Assets".
/// </summary>
[RequireComponent(typeof(Rigidbody2D))]
public class Block : MonoBehaviour
{
    /// <summary>Off while building and while the castle settles at the start of the battle.</summary>
    public static bool DamageEnabled;

    public PieceMaterial material = PieceMaterial.Wood;
    public int team;                       // 0 = Red, 1 = Blue
    public int cols = 1, rows = 1;         // size in grid cells
    public float maxHealth = 40f;
    public Sprite[] damageSprites = new Sprite[3];   // cracked, broken, crumbling
    public bool isWaterBarrel;

    public float Health { get; private set; }
    public Rigidbody2D Body { get; private set; }

    SpriteRenderer sr;
    int stage;
    float lastHitSound;

    void Awake()
    {
        Body = GetComponent<Rigidbody2D>();
        sr = GetComponent<SpriteRenderer>();
        Health = maxHealth;
    }

    void OnCollisionEnter2D(Collision2D c)
    {
        if (!DamageEnabled) return;
        float impulse = 0f;
        for (int i = 0; i < c.contactCount; i++) impulse += c.GetContact(i).normalImpulse;
        float mult = 1f;
        var proj = c.collider.GetComponentInParent<Projectile>();
        if (proj != null) mult = proj.DamageMultiplier(this);
        float dmg = impulse * 4f * mult;
        if (dmg < 6f) return;
        if (Time.time - lastHitSound > 0.15f && GameAssets.I != null)
        {
            lastHitSound = Time.time;
            AudioManager.Play(GameAssets.I.HitSound(material), Mathf.Clamp01(dmg / 120f));
        }
        TakeDamage(dmg);
    }

    public void TakeDamage(float amount)
    {
        if (Health <= 0f) return;
        Health -= amount;
        float r = Health / maxHealth;
        int s = r < 0.25f ? 3 : r < 0.5f ? 2 : r < 0.75f ? 1 : 0;
        if (s != stage && sr != null)
        {
            stage = s;
            if (s > 0 && damageSprites != null && damageSprites.Length >= s && damageSprites[s - 1] != null)
                sr.sprite = damageSprites[s - 1];
            Fx.Dust(transform.position, 0.8f);
        }
        if (Health <= 0f) Break();
    }

    public void Ignite()
    {
        if (material == PieceMaterial.Wood && !isWaterBarrel) Burning.Ignite(this);
    }

    public void Break()
    {
        Vector2 p = transform.position;
        Fx.Debris(p, material, Mathf.Clamp(cols * rows * 2, 3, 10));
        Fx.Dust(p, 1.2f + 0.3f * Mathf.Max(cols, rows));
        if (GameAssets.I != null) AudioManager.Play(GameAssets.I.BreakSound(material), 0.9f);
        if (isWaterBarrel)
        {
            Fx.Splash(p);
            if (GameAssets.I != null) AudioManager.Play(GameAssets.I.splashSfx);
            foreach (var b in FindCompat.All<Burning>())
                if (Vector2.Distance(b.transform.position, p) < 3.5f) b.Extinguish();
        }
        Destroy(gameObject);
    }
}
